"""Builds the deck's antialiased Noto Sans fonts as TFT_eSPI smooth-font (VLW) arrays.

    pip install Pillow
    python tools/make_smooth_fonts.py [--fonts-dir C:/Windows/Fonts]

Writes src/fonts/noto_*.h. Noto Sans is under the SIL Open Font License 1.1
(see src/fonts/NOTICE.md), so the generated arrays may live in the repo.

VLW layout read by TFT_eSPI loadFont()/loadMetrics(), all big-endian int32:
  header: glyph count, version (11), size, 0, ascent ("d"), descent ("p")
  per glyph, sorted by code point: unicode, height, width, xAdvance,
                                    dY (bitmap top above baseline), dX, 0
  then each glyph's 8-bit alpha bitmap, width * height bytes, same order.
"""
from __future__ import annotations

import argparse
import struct
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

OUT_DIR = Path(__file__).resolve().parents[1] / "src" / "fonts"

ASCII = "".join(chr(c) for c in range(0x20, 0x7F))
# Everything sanitizeVi() lets through (src/text_vi.cpp), so no glyph is ever missing.
VIETNAMESE = (
    ASCII
    + "".join(chr(c) for c in range(0xC0, 0x180) if c not in (0xD7, 0xF7))
    + "\u01A0\u01A1\u01AF\u01B0"
    + "".join(chr(c) for c in range(0x1EA0, 0x1EFA))
)
CHARSETS = {
    "ui": ASCII + "\u00B0",
    "vi": VIETNAMESE + "\u00B0",
    "digits": "0123456789:-. ",
}

# (array name, file name, ttf, pixel size, charset)
FONTS = [
    ("NOTO_TINY", "noto_tiny.h", "NotoSans-Regular.ttf", 10, "ui"),
    ("NOTO_SMALL", "noto_small.h", "NotoSans-Regular.ttf", 12, "ui"),
    ("NOTO_BODY", "noto_body.h", "NotoSans-Regular.ttf", 15, "vi"),
    ("NOTO_BODY_BOLD", "noto_body_bold.h", "NotoSans-Bold.ttf", 15, "vi"),
    ("NOTO_LARGE", "noto_large.h", "NotoSans-Bold.ttf", 22, "ui"),
    ("NOTO_HUGE", "noto_huge.h", "NotoSans-Bold.ttf", 52, "digits"),
]


def charset(name: str) -> str:
    return CHARSETS[name]


def glyph(font: ImageFont.FreeTypeFont, ch: str) -> tuple[tuple[int, ...], bytes]:
    """(unicode, height, width, xAdvance, dY, dX, 0) and the alpha bitmap."""
    advance = round(font.getlength(ch))
    x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
    w, h = x1 - x0, y1 - y0
    if w <= 0 or h <= 0:
        return (ord(ch), 0, 0, advance, 0, 0, 0), b""
    image = Image.new("L", (w, h), 0)
    ImageDraw.Draw(image).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
    if image.getbbox() is None:  # blank (e.g. a space with a box)
        return (ord(ch), 0, 0, advance, 0, 0, 0), b""
    return (ord(ch), h, w, advance, -y0, x0, 0), image.tobytes()


def build_vlw(ttf: Path, size: int, chars: str) -> bytes:
    font = ImageFont.truetype(str(ttf), size)
    ascent = -font.getbbox("d", anchor="ls")[1]
    descent = font.getbbox("p", anchor="ls")[3]
    glyphs = [glyph(font, ch) for ch in sorted(set(chars))]
    out = bytearray(struct.pack(">6i", len(glyphs), 11, size, 0, ascent, descent))
    for record, _ in glyphs:
        out += struct.pack(">7i", *record)
    for _, bitmap in glyphs:
        out += bitmap
    return bytes(out)


def c_header(name: str, data: bytes) -> str:
    rows = (", ".join(f"0x{b:02X}" for b in data[i:i + 20]) for i in range(0, len(data), 20))
    return (
        "// Generated by tools/make_smooth_fonts.py from Noto Sans (SIL OFL 1.1, see NOTICE.md).\n"
        "#pragma once\n#include <Arduino.h>\n\n"
        f"const uint8_t {name}[] PROGMEM = {{\n    " + ",\n    ".join(rows) + "\n};\n"
    )


def notice(ttf: Path) -> str:
    # Pillow has no name-table API: read copyright (0), license (13) and URL (14) directly.
    data = ttf.read_bytes()
    num = struct.unpack(">H", data[4:6])[0]
    tables = {data[12 + 16 * i:16 + 16 * i].decode("latin-1"): struct.unpack(">II", data[20 + 16 * i:28 + 16 * i])
              for i in range(num)}
    offset, _ = tables["name"]
    count, strings = struct.unpack(">HH", data[offset + 2:offset + 6])
    names = {}
    for i in range(count):
        pid, _, lang, nid, length, off = struct.unpack(">6H", data[offset + 6 + 12 * i:offset + 18 + 12 * i])
        if pid == 3 and lang == 0x409 and nid in (0, 13, 14):
            raw = data[offset + strings + off:offset + strings + off + length]
            names[nid] = raw.decode("utf-16-be")
    return (
        "# Fonts\n\n"
        "The arrays in this folder are generated by `tools/make_smooth_fonts.py` from\n"
        "Noto Sans Regular and Bold.\n\n"
        f"{names.get(0, '')}\n\n{names.get(13, '')}\n\n{names.get(14, '')}\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--fonts-dir", type=Path, default=Path("C:/Windows/Fonts"))
    args = parser.parse_args()
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    total = 0
    for name, file_name, ttf, size, chars in FONTS:
        vlw = build_vlw(args.fonts_dir / ttf, size, charset(chars))
        (OUT_DIR / file_name).write_text(c_header(name, vlw), encoding="utf-8")
        total += len(vlw)
        print(f"{file_name}: {len(charset(chars))} glyphs, {len(vlw) // 1024} KB")
    (OUT_DIR / "NOTICE.md").write_text(notice(args.fonts_dir / "NotoSans-Regular.ttf"), encoding="utf-8")
    print(f"total {total // 1024} KB of flash")


if __name__ == "__main__":
    main()
