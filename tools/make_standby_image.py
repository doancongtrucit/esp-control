"""Turn your own picture into the deck's standby background.

    pip install Pillow
    python tools/make_standby_image.py path/to/picture.jpg [--focus 1.0]

Writes src/standby_image.h: a 320x240 RGB565 array (about 150 KB of flash),
cropped to 4:3 and darkened on the right where the clock column is drawn.
The header is git-ignored on purpose: pictures you use are usually someone
else's work, so they stay on your PC. Without the header the firmware draws a
plain gradient instead.
"""
from __future__ import annotations

import argparse
from pathlib import Path

from PIL import Image

W, H = 320, 240
SHADE_FROM_X = 200  # right column darkens from here to the edge
SHADE_MAX = 190     # out of 255 at the right edge
OUT = Path(__file__).resolve().parents[1] / "src" / "standby_image.h"


def crop_4_3(image: Image.Image, focus: float) -> Image.Image:
    """Largest 4:3 crop; `focus` slides it from the left (0) to the right (1) edge."""
    width, height = image.size
    if width * 3 >= height * 4:
        crop_w, crop_h = height * 4 // 3, height
    else:
        crop_w, crop_h = width, width * 3 // 4
    x0 = round((width - crop_w) * min(max(focus, 0.0), 1.0))
    y0 = (height - crop_h) // 2
    return image.crop((x0, y0, x0 + crop_w, y0 + crop_h)).resize((W, H), Image.LANCZOS)


def shade_right(image: Image.Image) -> Image.Image:
    pixels = image.load()
    for x in range(SHADE_FROM_X, W):
        keep = 1 - SHADE_MAX / 255 * (x - SHADE_FROM_X) / (W - SHADE_FROM_X)
        for y in range(H):
            r, g, b = pixels[x, y]
            pixels[x, y] = (int(r * keep), int(g * keep), int(b * keep))
    return image


def rgb565(r: int, g: int, b: int) -> int:
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def header(image: Image.Image) -> str:
    values = [rgb565(*image.getpixel((x, y))) for y in range(H) for x in range(W)]
    rows = (", ".join(f"0x{v:04X}" for v in values[i:i + 16]) for i in range(0, len(values), 16))
    return (
        "// Generated by tools/make_standby_image.py. Personal picture: git-ignored, do not commit.\n"
        "#pragma once\n#include <Arduino.h>\n\n"
        f"constexpr int STANDBY_IMAGE_W = {W};\nconstexpr int STANDBY_IMAGE_H = {H};\n"
        "const uint16_t STANDBY_IMAGE[] PROGMEM = {\n    " + ",\n    ".join(rows) + "\n};\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("picture", type=Path)
    parser.add_argument("--focus", type=float, default=1.0,
                        help="horizontal crop position, 0 = left edge, 1 = right edge (default)")
    args = parser.parse_args()
    image = shade_right(crop_4_3(Image.open(args.picture).convert("RGB"), args.focus))
    OUT.write_text(header(image), encoding="utf-8")
    print(f"Wrote {OUT} ({W}x{H})")


if __name__ == "__main__":
    main()
